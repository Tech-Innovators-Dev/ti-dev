#!/bin/sh
# Build dist/ti-workspace-kit.md: one deterministic file with README,
# BOOTSTRAP, HANDOFF, guidelines 00-19, CHANGELOG, the manifest template and LICENSE.
# Links between bundled files become in-bundle anchors; links to other files
# are rewritten relative to dist/.
# Usage: scripts/build-bundle.sh [output-path]   (run from the repo root)
set -eu
LC_ALL=C
export LC_ALL

out=${1:-dist/ti-workspace-kit.md}
[ -f VERSION ] || { echo "build-bundle: run from the repo root (VERSION not found)" >&2; exit 1; }
version=$(sed -n '1p' VERSION)

files="README.md BOOTSTRAP.md HANDOFF.md"
for f in guidelines/[0-9][0-9]-*.md; do
  files="$files $f"
done
files="$files CHANGELOG.md"
template=templates/manifest.template.yaml
for f in LICENSE "$template"; do
  [ -f "$f" ] || { echo "build-bundle: missing $f" >&2; exit 1; }
done

anchor() { printf 'kit-%s' "$1" | sed 's/\.md$//; s/[^A-Za-z0-9]/-/g' | tr 'A-Z' 'a-z'; }

title() {
  # First level-1 heading after any leading metadata block; else the path.
  t=$(awk '/^# /{sub(/^# /,""); print; exit}' "$1")
  [ -n "$t" ] && printf '%s' "$t" || printf '%s' "$1"
}

tmp="$out.tmp.$$"
mkdir -p "$(dirname "$out")"
{
  printf '# ti-workspace kit %s\n\n' "$version"
  printf 'Single-file bundle generated by scripts/build-bundle.sh. Do not edit by hand; edit the sources and rebuild.\n\n'
  printf '## Contents\n\n'
  for f in $files; do
    printf -- '- [%s](#%s) (`%s`)\n' "$(title "$f")" "$(anchor "$f")" "$f"
  done
  printf -- '- [Manifest template](#%s) (`%s`)\n' "$(anchor "$template")" "$template"
  printf -- '- [License](#kit-license) (`LICENSE`)\n'
  for f in $files; do
    printf '\n---\n\n<a id="%s"></a>\n\n' "$(anchor "$f")"
    awk -v src="$f" -v known="$files" '
      function norm(p,   n, i, a, out, k, s) {
        n = split(p, a, "/"); k = 0
        for (i = 1; i <= n; i++) {
          if (a[i] == "" || a[i] == ".") continue
          if (a[i] == "..") { if (k > 0) k--; continue }
          s[++k] = a[i]
        }
        out = ""
        for (i = 1; i <= k; i++) out = out (i > 1 ? "/" : "") s[i]
        return out
      }
      function anchor(p,   a) {
        a = p; sub(/\.md$/, "", a); gsub(/[^A-Za-z0-9]/, "-", a)
        return "kit-" tolower(a)
      }
      BEGIN {
        nk = split(known, ks, " "); for (i = 1; i <= nk; i++) isknown[ks[i]] = 1
        dir = src; if (dir ~ /\//) sub(/\/[^\/]*$/, "", dir); else dir = ""
      }
      # Strip YAML metadata block at the top of a file.
      NR == 1 && /^---$/ { inmeta = 1; next }
      inmeta { if (/^---$/) inmeta = 0; next }
      /^```/ { fence = !fence; print; next }
      fence { print; next }
      {
        line = $0; res = ""
        while (match(line, /\]\([^)#: ]+\.md(#[^)]*)?\)/)) {
          tok = substr(line, RSTART + 2, RLENGTH - 3)
          path = tok; sub(/#.*/, "", path)
          full = norm((dir == "" ? "" : dir "/") path)
          if (full in isknown) rep = "](#" anchor(full) ")"
          else rep = "](../" full substr(tok, length(path) + 1) ")"
          res = res substr(line, 1, RSTART - 1) rep
          line = substr(line, RSTART + RLENGTH)
        }
        print res line
      }
    ' "$f"
  done
  printf '\n---\n\n<a id="%s"></a>\n\n' "$(anchor "$template")"
  printf '# Manifest template\n\nSource: `%s`. Copy it into the project and fill it in during setup.\n\n' "$template"
  printf '```yaml\n'
  cat "$template"
  printf '```\n'
  # The license travels with the bundle, so a standalone copy keeps the notice.
  printf '\n---\n\n<a id="kit-license"></a>\n\n# License\n\nSource: `LICENSE`.\n\n'
  printf '```text\n'
  cat LICENSE
  printf '```\n'
} | sed 's/](LICENSE)/](#kit-license)/g' > "$tmp"
mv "$tmp" "$out"
echo "build-bundle: wrote $out (version $version)"
